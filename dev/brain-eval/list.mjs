// The whole scenario library in one readable page, for the owner's review: `node dev/brain-eval/list.mjs > dev/brain-eval/scenarios/REVIEW.md`.
import { fileURLToPath } from 'node:url';
import { loadScenarios } from './scenario.mjs';

const quote = (phrases) => phrases.map((p) => JSON.stringify(p)).join(' or ');

export function formatListing(scenarios) {
  const notes = scenarios.reduce((n, s) => n + s.notes.length, 0);
  const questions = scenarios.reduce((n, s) => n + s.questions.length, 0);
  const out = [
    '# The scenario library, for review',
    '',
    `Generated by \`node dev/brain-eval/list.mjs\`; a test fails if this file is out of date. ${scenarios.length} scenarios, ${notes} notes, ${questions} questions. All text is invented.`,
    '',
    'For each question: the answer must contain one phrase from every **must** group, and must not give any **stale** phrase as current (mentioning it as the old value is fine).',
  ];
  for (const s of scenarios) {
    out.push('', `## ${s.id}: ${s.title}`, '', s.description ?? '', '', '### Notes', '');
    for (const n of s.notes) out.push(`- ${n.id} · ${n.at} · ${n.text}`);
    out.push('', '### Questions', '');
    for (const q of s.questions) {
      out.push(`- **${q.id}** (${q.kind}, asked after ${q.after}${q.at === undefined ? '' : ` at ${q.at}`}): ${q.ask}`);
      if (q.expectNothing === true) out.push('  - the right answer is that nothing relevant is known');
      for (const g of q.must ?? []) out.push(`  - must: ${quote(g)}`);
      if (q.stale !== undefined) out.push(`  - stale: ${quote(q.stale)}`);
      if (q.why !== undefined) out.push(`  - why: ${q.why}`);
    }
  }
  return `${out.join('\n')}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const loaded = loadScenarios(fileURLToPath(new URL('./scenarios', import.meta.url)));
  if (!loaded.ok) {
    process.stderr.write(`${loaded.problems.join('\n')}\n`);
    process.exitCode = 2;
  } else process.stdout.write(formatListing(loaded.scenarios));
}
